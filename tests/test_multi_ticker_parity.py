"""
Multi-Ticker Signal Parity Test (AlphaLab oracle)

Compares AlphaLive's signal engine bar-by-bar with AlphaLab's on SPY and
MSFT daily fixtures (2022-2023), for all 7 daily strategies.

Independence: tests/fixtures/expected_signals_{TICKER}_{strategy}.csv and
signal_parity_manifest.json are generated by AlphaLab's own code
(AlphaLab/scripts/generate_signal_parity_fixtures.py) - never by AlphaLive.
AlphaLive is configured with the manifest's `alphalive_params`, i.e. the
parameters AlphaLab's export contract produces from the same AlphaLab
parameters, so this checks the export mapping as well as the logic.

Metrics (see measure_parity): agreement across ALL bars (dominated by
HOLD-HOLD bars, so near 100% even for badly divergent logic) and agreement
on DECISION bars (bars where either engine emits BUY/SELL). The test
requires zero decision mismatches. AlphaLive's live-only bear-market entry
filter is disabled here; its effect is measured separately.

Usage:
    pytest tests/test_multi_ticker_parity.py -v
"""

